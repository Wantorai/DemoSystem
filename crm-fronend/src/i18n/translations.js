export const language = ["eng", "en"].includes(
  String(process.env.NEXT_PUBLIC_LANGUAGE || "ru").trim().toLowerCase()
) ? "eng" : "ru";

const interpolationRules = [
  [/^Ошибка:\s*/u, "Error: "],
  [/^Заказ №\s*/u, "Order #"],
  [/^Клиент №\s*/u, "Client #"],
  [/^Объект надстройки №\s*/u, "Add-on item #"],
  [/^Подрядчик №\s*/u, "Contractor #"],
  [/^Поставщик фасадов №\s*/u, "Facade supplier #"],
  [/^Поставщик фурнитуры №\s*/u, "Hardware supplier #"],
  [/^Технолог №\s*/u, "Technologist #"],
  [/^Установщик №\s*/u, "Installer #"],
];

export function translate(value) {
  if (language === "ru" || typeof value !== "string" || !/[А-Яа-яЁё]/u.test(value)) return value;
  const leading = value.match(/^\s*/u)?.[0] || "";
  const trailing = value.match(/\s*$/u)?.[0] || "";
  const text = value.trim();
  if (!text) return value;
  if (english[text]) return `${leading}${english[text]}${trailing}`;
  for (const [pattern, replacement] of interpolationRules) {
    if (pattern.test(text)) return `${leading}${text.replace(pattern, replacement)}${trailing}`;
  }
  return value;
}
